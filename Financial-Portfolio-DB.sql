CREATE DATABASE IF NOT EXISTS FINANCIAL_DB;
USE FINANCIAL_DB;

-- Disable FK checks temporarily for clean initialization
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS TRANSACTION;
DROP TABLE IF EXISTS TECHNICAL_SIGNALS;
DROP TABLE IF EXISTS REPORT;
DROP TABLE IF EXISTS COMPANY;
DROP TABLE IF EXISTS ADMIN;
DROP TABLE IF EXISTS ADMINISTRATOR;
DROP TABLE IF EXISTS USER;

SET FOREIGN_KEY_CHECKS = 1;

-- 1. USER / CLIENT TABLE (CUST_EMAIL IS PRIMARY KEY)
CREATE TABLE USER (
    CUST_EMAIL VARCHAR(100) NOT NULL PRIMARY KEY,
    UID INT NOT NULL AUTO_INCREMENT UNIQUE, 
    USERNAME VARCHAR(100) NOT NULL,
    PHONE VARCHAR(15) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL
);

-- 2. ADMIN TABLE (ADMIN_EMAIL IS PRIMARY KEY)
CREATE TABLE ADMIN (
    ADMIN_EMAIL VARCHAR(100) NOT NULL PRIMARY KEY,
    ADMINID INT NOT NULL AUTO_INCREMENT UNIQUE,
    ADMINNAME VARCHAR(100) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL
);

-- Compatibility View for ADMINISTRATOR
CREATE OR REPLACE VIEW ADMINISTRATOR AS SELECT * FROM ADMIN;

-- 3. COMPANY / STOCK TABLE
CREATE TABLE COMPANY (
    CID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CNAME VARCHAR(100) NOT NULL,
    CAPITAL DECIMAL(15,2) NOT NULL,
    SECTOR VARCHAR(100) NOT NULL
);

-- 4. FUNDAMENTAL FINANCIAL REPORT TABLE
CREATE TABLE REPORT (
    REPORT_ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    LTP DECIMAL(10,2) NOT NULL,
    EPS DECIMAL(10,2) NOT NULL,
    ROE DECIMAL(10,2) NOT NULL,
    CID INT NOT NULL,
    FOREIGN KEY (CID) REFERENCES COMPANY(CID) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 5. TECHNICAL SIGNALS & QUANTITATIVE ANALYSIS TABLE
CREATE TABLE TECHNICAL_SIGNALS (
    STOCK_ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ADX DECIMAL(10,2) NOT NULL,
    VOLUME INT NOT NULL,
    MACD DECIMAL(10,2) NOT NULL,
    CID INT NOT NULL,
    FOREIGN KEY (CID) REFERENCES COMPANY(CID) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 6. TRANSACTIONS & ORDER BOOK TABLE
CREATE TABLE TRANSACTION (
    TID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    UID INT NOT NULL,
    CID INT NOT NULL,
    RATE DECIMAL(10,2) NOT NULL,
    QUANTITY INT NOT NULL,
    BUY_SELL VARCHAR(10) NOT NULL CHECK (BUY_SELL IN ('BUY', 'SELL')),
    FOREIGN KEY (UID) REFERENCES USER(UID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (CID) REFERENCES COMPANY(CID) ON DELETE CASCADE ON UPDATE CASCADE
);